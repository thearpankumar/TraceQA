//! The Python page object (Playwright's sync API). Plain string building; no template engine.

use std::fmt::Write as _;

use traceqa_common::locator::py_string;

use super::{is_component_id, Entry, Plan};

pub(super) fn file_name(plan: &Plan) -> String {
    format!("{}_page.py", plan.stem.replace('-', "_"))
}

/// The expression with `page` turned into `self.page`.
fn expression(entry: &Entry) -> String {
    let code = entry.locator.playwright_py();
    if let Some(rest) = code.strip_prefix("page.") {
        format!("self.page.{rest}")
    } else if let Some(rest) = code.strip_prefix("frame_by_label(page,") {
        format!("frame_by_label(self.page,{rest}")
    } else {
        code
    }
}

fn properties(plan: &Plan) -> String {
    let mut out = String::new();
    for entry in &plan.entries {
        let _ = writeln!(out, "    # traceqa:id {}", entry.id);
        let _ = writeln!(
            out,
            "    # role: {}, name: {}",
            py_string(&entry.role),
            py_string(&entry.name)
        );
        if entry.locator.forced {
            let _ = writeln!(
                out,
                "    # FORCED: nothing readable tells this apart, so this CSS selector is used. It breaks when the page layout changes."
            );
        } else if !entry.unique {
            let also: Vec<&str> = entry
                .locator
                .ambiguous_with
                .iter()
                .map(String::as_str)
                .filter(|id| is_component_id(id))
                .collect();
            let _ = writeln!(
                out,
                "    # AMBIGUOUS: this may also match other components{}{}. Add a test id to the page to tell them apart.",
                if also.is_empty() { "" } else { ": " },
                also.join(", ")
            );
        }
        if entry.differs {
            let _ = writeln!(
                out,
                "    # DIFFERS: the browsers did not agree how to find this; the locator with the most scope is used."
            );
        }
        if entry.present_in.len() < plan.targets.len() {
            let targets: Vec<String> = entry.present_in.iter().map(|t| py_string(t)).collect();
            let _ = writeln!(out, "    # Only found in: {}", targets.join(", "));
        }
        let _ = writeln!(out, "    @property");
        let _ = writeln!(out, "    def {}(self) -> Locator:", entry.ident_py());
        if entry.multi > 1 {
            let _ = writeln!(
                out,
                "        \"\"\"A multi-match locator: the page had {} of these. Use all(), count() or filter().\"\"\"",
                entry.multi
            );
        }
        let _ = writeln!(out, "        return {}\n", expression(entry));
    }
    out
}

pub(super) fn render(plan: &Plan) -> String {
    let targets: Vec<String> = plan.targets.iter().map(|t| py_string(t)).collect();
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by traceqa codegen. Regenerate instead of editing by hand."
    );
    let _ = writeln!(out, "# Run {}, page {}", py_string(&plan.run_id), py_string(&plan.url));
    let _ = writeln!(out, "# Read in: {}", targets.join(", "));
    let _ = writeln!(
        out,
        "# Names are matched exactly, so they depend on the page's language: generate again for another locale."
    );
    let _ = writeln!(
        out,
        "# Each property is marked with traceqa:id so tools can find and update it."
    );
    let _ = writeln!(out, "from __future__ import annotations\n");
    let _ = writeln!(out, "import re\nimport unicodedata\n");
    let _ = writeln!(out, "from playwright.sync_api import Frame, Locator, Page\n\n");
    out.push_str(FRAME_HELPER);
    let _ = writeln!(out, "class {}:", plan.class_name);
    let _ = writeln!(out, "    def __init__(self, page: Page) -> None:");
    let _ = writeln!(out, "        self.page = page\n");
    out.push_str(&properties(plan));
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

/// The label of a frame is its name, else the path of its URL, lower case with whitespace
/// squashed; that is how the engine writes it in a component's path.
const FRAME_HELPER: &str = r#"def _squash(text: str) -> str:
    return " ".join(unicodedata.normalize("NFC", text).split()).lower()


def _frame_label(frame: Frame) -> str:
    if frame.name:
        return frame.name
    url = frame.url
    scheme = url.find("://")
    rest = url[scheme + 3 :] if scheme >= 0 else url
    slash = rest.find("/")
    return re.split(r"[?#]", rest[slash:] if slash >= 0 else "/")[0]


def frame_by_label(page: Page, label: str) -> Frame:
    """The frame a component was found in, by the label its path carries."""
    wanted = _squash(label)
    for frame in page.frames:
        if frame != page.main_frame and _squash(_frame_label(frame)) == wanted:
            return frame
    raise LookupError(f"No frame labelled {label!r} on the page")


"#;
