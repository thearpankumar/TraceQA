//! The TypeScript page object. Plain string building; no template engine.

use std::fmt::Write as _;

use traceqa_common::locator::ts_string;

use super::{is_component_id, Entry, Plan};

pub(super) fn file_name(plan: &Plan) -> String {
    format!("{}.page.ts", plan.stem)
}

/// The expression with `page` turned into `this.page`.
fn expression(entry: &Entry) -> String {
    let code = entry.locator.playwright_ts();
    if let Some(rest) = code.strip_prefix("page.") {
        format!("this.page.{rest}")
    } else if let Some(rest) = code.strip_prefix("frameByLabel(page,") {
        format!("frameByLabel(this.page,{rest}")
    } else {
        code
    }
}

fn properties(plan: &Plan) -> String {
    let mut out = String::new();
    for entry in &plan.entries {
        let _ = writeln!(out, "  // traceqa:id {}", entry.id);
        let _ = writeln!(
            out,
            "  // role: {}, name: {}",
            ts_string(&entry.role),
            ts_string(&entry.name)
        );
        if entry.locator.forced {
            let _ = writeln!(
                out,
                "  // FORCED: nothing readable tells this apart, so this CSS selector is used. It breaks when the page layout changes."
            );
        } else if !entry.unique {
            let also: Vec<&str> = entry
                .locator
                .ambiguous_with
                .iter()
                .map(String::as_str)
                .filter(|id| is_component_id(id))
                .collect();
            let _ = writeln!(
                out,
                "  // AMBIGUOUS: this may also match other components{}{}. Add a test id to the page to tell them apart.",
                if also.is_empty() { "" } else { ": " },
                also.join(", ")
            );
        }
        if entry.differs {
            let _ = writeln!(
                out,
                "  // DIFFERS: the browsers did not agree how to find this; the locator with the most scope is used."
            );
        }
        if entry.present_in.len() < plan.targets.len() {
            let targets: Vec<String> = entry.present_in.iter().map(|t| ts_string(t)).collect();
            let _ = writeln!(out, "  // Only found in: {}", targets.join(", "));
        }
        if entry.multi > 1 {
            let _ = writeln!(
                out,
                "  /** A multi-match locator: the page had {} of these. Use all(), count() or filter(). */",
                entry.multi
            );
        }
        let _ = writeln!(out, "  get {}(): Locator {{", entry.ident_ts());
        let _ = writeln!(out, "    return {};", expression(entry));
        let _ = writeln!(out, "  }}\n");
    }
    out
}

pub(super) fn render(plan: &Plan) -> String {
    let targets: Vec<String> = plan.targets.iter().map(|t| ts_string(t)).collect();
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by traceqa codegen. Regenerate instead of editing by hand."
    );
    let _ = writeln!(out, "// Run {}, page {}", ts_string(&plan.run_id), ts_string(&plan.url));
    let _ = writeln!(out, "// Read in: {}", targets.join(", "));
    let _ = writeln!(
        out,
        "// Names are matched exactly, so they depend on the page's language: generate again for another locale."
    );
    let _ = writeln!(
        out,
        "// Each property is marked with traceqa:id so tools can find and update it."
    );
    let _ = writeln!(
        out,
        "import type {{ Frame, Locator, Page }} from \"@playwright/test\";\n"
    );
    out.push_str(FRAME_HELPER);
    let _ = writeln!(out, "export class {} {{", plan.class_name);
    // No parameter property: type stripping (node --check, tests) only removes annotations.
    let _ = writeln!(out, "  readonly page: Page;\n");
    let _ = writeln!(out, "  constructor(page: Page) {{\n    this.page = page;\n  }}\n");
    out.push_str(&properties(plan));
    let _ = writeln!(out, "}}");
    out
}

/// The label of a frame is its name, else the path of its URL, lower case with whitespace
/// squashed; that is how the engine writes it in a component's path.
const FRAME_HELPER: &str = r#"function squash(text: string): string {
  return text.normalize("NFC").split(/\s+/).filter(Boolean).join(" ").toLowerCase();
}

function frameLabel(frame: Frame): string {
  const name = frame.name();
  if (name) return name;
  const url = frame.url();
  const scheme = url.indexOf("://");
  const rest = scheme >= 0 ? url.slice(scheme + 3) : url;
  const slash = rest.indexOf("/");
  return (slash >= 0 ? rest.slice(slash) : "/").split(/[?#]/)[0];
}

/** The frame a component was found in, by the label its path carries. */
export function frameByLabel(page: Page, label: string): Frame {
  const wanted = squash(label);
  const found = page.frames().find((frame) => frame !== page.mainFrame() && squash(frameLabel(frame)) === wanted);
  if (!found) throw new Error(`No frame labelled ${JSON.stringify(label)} on the page`);
  return found;
}

"#;
